create or replace function public.current_user_role()
returns public.user_role
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.profiles as p
  where p.id = (select auth.uid())
    and p.is_active = true
$$;

create or replace function public.log_inventory_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  before_row jsonb;
  after_row jsonb;
  changed_id uuid;
  changed_action text := tg_op;
  actor_display_name text;
begin
  if tg_op = 'INSERT' then
    after_row := to_jsonb(new);
    changed_id := new.id;
  elsif tg_op = 'UPDATE' then
    before_row := to_jsonb(old);
    after_row := to_jsonb(new);
    changed_id := new.id;
  else
    before_row := to_jsonb(old);
    changed_id := old.id;
  end if;

  select p.full_name into actor_display_name
  from public.profiles as p
  where p.id = actor;

  insert into public.audit_logs (
    table_name, record_id, action, actor_id, actor_name, old_data, new_data
  ) values (
    tg_table_name,
    changed_id,
    changed_action,
    actor,
    coalesce(actor_display_name, 'System / unknown user'),
    before_row,
    after_row
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists products_audit_changes on public.products;
create trigger products_audit_changes
after insert or update or delete on public.products
for each row execute function public.log_inventory_changes();

drop trigger if exists raw_materials_audit_changes on public.raw_materials;
create trigger raw_materials_audit_changes
after insert or update or delete on public.raw_materials
for each row execute function public.log_inventory_changes();

