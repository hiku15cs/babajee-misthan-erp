create policy "Profiles are visible to self and owners"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.current_user_role()) = 'OWNER');

create policy "Owners manage profiles"
on public.profiles for all to authenticated
using ((select public.current_user_role()) = 'OWNER')
with check ((select public.current_user_role()) = 'OWNER');

create policy "Authenticated users read active products"
on public.products for select to authenticated
using (is_active or (select public.current_user_role()) in ('OWNER', 'MANAGER'));

create policy "Owners and managers manage products"
on public.products for all to authenticated
using ((select public.current_user_role()) in ('OWNER', 'MANAGER'))
with check ((select public.current_user_role()) in ('OWNER', 'MANAGER'));

create policy "Authenticated users read available product batches"
on public.product_batches for select to authenticated
using (
  quantity_remaining > 0
  or (select public.current_user_role()) in ('OWNER', 'MANAGER')
);

create policy "Owners and managers manage product batches"
on public.product_batches for all to authenticated
using ((select public.current_user_role()) in ('OWNER', 'MANAGER'))
