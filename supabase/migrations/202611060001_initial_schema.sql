create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null,
  role public.user_role not null default 'STAFF',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  product_type public.product_type not null,
  sku text unique,
  barcode text unique,
  unit text not null default 'piece',
  price_per_unit numeric(12, 2) not null check (price_per_unit >= 0),
  is_active boolean not null default true,
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_batches (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete restrict,
  batch_number text,
  quantity_received numeric(12, 3) not null check (quantity_received > 0),
  quantity_remaining numeric(12, 3) not null check (quantity_remaining >= 0),
  unit_cost numeric(12, 2) not null default 0 check (unit_cost >= 0),
  received_at timestamptz not null default now(),
  expiry_date date,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint product_batches_remaining_lte_received
    check (quantity_remaining <= quantity_received)
);

create table if not exists public.raw_materials (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category public.material_category not null,
  unit text not null,
  quantity_on_hand numeric(12, 3) not null default 0 check (quantity_on_hand >= 0),
  purchase_price_per_unit numeric(12, 2) not null default 0
    check (purchase_price_per_unit >= 0),
  vendor_name text,
  last_received_at timestamptz,
  is_active boolean not null default true,
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id uuid primary key default gen_random_uuid(),
  transaction_number bigint generated by default as identity unique,
  cashier_id uuid references public.profiles (id) on delete set null,
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  discount numeric(12, 2) not null default 0 check (discount >= 0),
  tax numeric(12, 2) not null default 0 check (tax >= 0),
  total numeric(12, 2) not null check (total >= 0),
  payment_mode public.payment_mode not null,
  output_mode public.output_mode not null default 'SILENT',
  status text not null default 'COMPLETED'
    check (status in ('COMPLETED', 'VOIDED', 'REFUNDED')),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.transaction_items (
  id uuid primary key default gen_random_uuid(),
  transaction_id uuid not null references public.transactions (id) on delete cascade,
  product_id uuid references public.products (id) on delete set null,
  product_batch_id uuid references public.product_batches (id) on delete set null,
  product_name text not null,
  quantity numeric(12, 3) not null check (quantity > 0),
  unit text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  line_total numeric(12, 2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.transaction_payments (
  id uuid primary key default gen_random_uuid(),
  transaction_id uuid not null references public.transactions (id) on delete cascade,
  payment_mode public.payment_mode not null check (payment_mode <> 'SPLIT'),
  amount numeric(12, 2) not null check (amount > 0),
  reference text,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated always as identity primary key,
  table_name text not null,
  record_id uuid not null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  actor_id uuid references public.profiles (id) on delete set null,
  actor_name text not null,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

create index if not exists product_batches_fefo_idx
  on public.product_batches (product_id, expiry_date, received_at)
  where quantity_remaining > 0;
create index if not exists transactions_created_at_idx
  on public.transactions (created_at desc);
create index if not exists transaction_items_transaction_id_idx
  on public.transaction_items (transaction_id);
create index if not exists transaction_payments_transaction_id_idx
  on public.transaction_payments (transaction_id);
create index if not exists audit_logs_table_record_idx
  on public.audit_logs (table_name, record_id, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row execute function public.touch_updated_at();

drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at
before update on public.products
for each row execute function public.touch_updated_at();

drop trigger if exists raw_materials_touch_updated_at on public.raw_materials;
