);

create policy "Staff and managers create transactions"
on public.transactions for insert to authenticated
with check (
  cashier_id = (select auth.uid())
  and (select public.current_user_role()) in ('OWNER', 'MANAGER', 'STAFF')
);

create policy "Owners void or update transactions"
on public.transactions for update to authenticated
using ((select public.current_user_role()) = 'OWNER')
with check ((select public.current_user_role()) = 'OWNER');

create policy "Users read items for accessible transactions"
on public.transaction_items for select to authenticated
using (
  exists (
    select 1 from public.transactions t
    where t.id = transaction_id
      and (
        t.cashier_id = (select auth.uid())
        or (select public.current_user_role()) = 'OWNER'
      )
  )
);

